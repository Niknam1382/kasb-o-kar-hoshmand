_DEFAULTS = {"sales": DEFAULT_GLOBAL_PROMPT_SALES, "consultation": DEFAULT_GLOBAL_PROMPT_CONSULTATION}


def _mode_value(tenant_mode) -> str:
    value = tenant_mode.value if hasattr(tenant_mode, "value") else tenant_mode
    return "consultation" if value == "consultation" else "sales"


def default_prompt_for(tenant_mode) -> str:
    return _DEFAULTS[_mode_value(tenant_mode)]


def resolve_global_prompt(admin_settings, tenant_mode) -> str:
    """مودِ ربات ← نسخه‌یِ همون مود (اگه غیرخالی) ← global_ai_system_prompt (قدیمی) ← پیش‌فرضِ حرفه‌ایِ همون مود."""
    mode = _mode_value(tenant_mode)
    specific = getattr(admin_settings, f"global_ai_prompt_{mode}", None)
    if specific and specific.strip():
        return specific
    legacy = getattr(admin_settings, "global_ai_system_prompt", None)
    if legacy and legacy.strip():
        return legacy
    return _DEFAULTS[mode]


def build_bot_tools(tenant_mode, support_enabled: bool, labels) -> list[str]:
    """خط‌هایِ بخشِ «ابزارهایِ ربات» — فقط دکمه‌هایی که واقعاً توی رباتِ همین فروشگاه هست.

    P24: در مودِ مشاوره «🗂 خدمات و بسته‌ها» از منو حذف شده (کاتالوگ در این مود بسته است ⇒
    فهرست همیشه خالی). اگر همین‌جا ذكرش می‌شد، هوش مصنوعی مشتری را به دکمه‌ای دعوت می‌کرد که
    وجود ندارد — یعنی همان «دکمهٔ مرده» در شکلِ گفتمانی.

    پ۱۰۸: «📦 سفارش‌هایِ من» در منویِ فروشگاهی هست ولی اینجا نبود ⇒ پرامپتِ فروش هم حق نداشت
    جز به همین فهرست اشاره کند. فهرست باید با `customer_main_keyboard` همسانی بماند (تستِ پ۱۰۸).
    """
    tools: list[str] = []
    if _mode_value(tenant_mode) != "consultation":
        tools = [
            f"«{labels.BTN_PRODUCTS}» — دیدنِ کاتالوگ",
            f"«{labels.BTN_CART}» — مرورِ سبد و تسویه‌حساب",
            f"«{labels.BTN_MY_ORDERS}» — سفارش‌هایِ خودت",
        ]
    if support_enabled:
        tools.append(f"«{labels.BTN_SUPPORT}» — ارتباط با فروشگاه")
    return tools
